const METRIC_META = {
  weight: { label: '体重', unit: 'kg' },
  height: { label: '身高', unit: 'cm' },
  head: { label: '头围', unit: 'cm' }
}

/** 月龄（可为小数）→ 相邻两月锚点线性插值 [p3,p15,p50,p85,p97] */
export function bandsAt(metric, gender, ageM) {
  const rows = (T[metric] || T.weight)[gender === 'girl' ? 'girl' : 'boy']
  /* 出生日期缺失/畸形时 ageM 是 NaN：Math.min/max 都会把 NaN 原样放过去，
     随后 rows[NaN] 取到 undefined，曲线页整页白屏——非有限值一律按月龄 0 处理 */
  const m = Math.max(0, Math.min(24, isFinite(ageM) ? ageM : 0))
  const lo = Math.floor(m)
  const hi = Math.min(24, lo + 1)
  const f = m - lo
  const a = rows[lo]
  const b = rows[hi]
  return a.map((v, i) => v + (b[i] - v) * f)
}

/**
 * 实测值 → 百分位（0–100）。
 * 锚点映射：P3→3, P15→15, P50→50, P85→85, P97→97；区间外按 ±2SD≈±1.88z 的斜率外推并夹紧。
 */
export function percentileOf(metric, gender, ageM, value) {
  const [p3, p15, p50, p85, p97] = bandsAt(metric, gender, ageM)
  const anchors = [[p3, 3], [p15, 15], [p50, 50], [p85, 85], [p97, 97]]
  if (value <= p3) {
    const slope = (15 - 3) / (p15 - p3)
    return Math.max(0.1, 3 - (p3 - value) * slope)
  }
  if (value >= p97) {
    const slope = (97 - 85) / (p97 - p85)
    return Math.min(99.9, 97 + (value - p97) * slope)
  }
  for (let i = 0; i < anchors.length - 1; i++) {
    const [x0, y0] = anchors[i]
    const [x1, y1] = anchors[i + 1]
    if (value >= x0 && value <= x1) return y0 + ((value - x0) / (x1 - x0)) * (y1 - y0)
  }
  return 50
}

/** 百分位 → 展示徽标（P50 附近显示 P50，其余取整十位） */
export function percentileBadge(p) {
  if (p >= 40 && p <= 60) return 'P50'
  const r = Math.round(p / 10) * 10
  return 'P' + Math.max(1, Math.min(99, r))
}

/** 通用曲线序列：ages 为升序小数月龄刻度，tolM 为实测点吸附容差（月） */
function series(metric, gender, points, ages, tolM) {
  const meta = METRIC_META[metric]
  const ref = { p3: [], p15: [], p50: [], p85: [], p97: [] }
  ages.forEach(a => {
    const [p3, p15, p50, p85, p97] = bandsAt(metric, gender, a)
    ref.p3.push(+p3.toFixed(1))
    ref.p15.push(+p15.toFixed(1))
    ref.p50.push(+p50.toFixed(1))
    ref.p85.push(+p85.toFixed(1))
    ref.p97.push(+p97.toFixed(1))
  })
  const baby = ages.map(a => {
    const near = points
      .map(p => ({ d: Math.abs(p.ageM - a), v: p.value }))
      .sort((x, y) => x.d - y.d)[0]
    return near && near.d <= tolM ? near.v : null
  })
  const vals = [...ref.p3, ...ref.p97, ...baby.filter(v => v != null)]
  const min = Math.floor(Math.min(...vals) * 2) / 2
  const max = Math.ceil(Math.max(...vals) * 2) / 2
  return { label: meta.label, unit: meta.unit, min, max, months: ages.length - 1, baby, ...ref }
}

/** 生成与原型 GROW 同形状的曲线数据（baby 取实测点，参考带取查表） */
export function chartData(metric, gender, points) {
  /* points: [{ageM, value}] 按月龄升序 */
  const maxAge = Math.max(6, ...points.map(p => Math.ceil(p.ageM)))
  const n = Math.min(24, maxAge)
  return series(metric, gender, points, Array.from({ length: n + 1 }, (_, i) => i), 0.6)
}

/**
 * 窗口曲线：X 轴按 fromM→toM 月龄均分为 ticks+1 个刻度，labels 为各刻度展示文本
 * （近 7 天用 '10.23'，近 N 月用 '5月'/'6月' 等真实日历月份）。
 * 吸附容差 tolM：天粒度默认半天（0.5/30.4375 月），月粒度传 0.5 月。
 */
export function chartDataDays(metric, gender, points, fromM, toM, ticks, labels, tolM = 0.5 / 30.4375) {
  const ages = Array.from({ length: ticks + 1 }, (_, i) => fromM + ((toM - fromM) * i) / ticks)
  const s = series(metric, gender, points, ages, tolM)
  s.labels = labels
  return s
}
